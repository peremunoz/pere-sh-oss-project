import type { APIRoute } from 'astro';
import contributions from '../data/contributions.json';
import { profileConfig } from '../config';

export const GET: APIRoute = async () => {
  const totalMerged = contributions.filter(c => c.status === 'merged').length;
  const totalOpen = contributions.filter(c => c.status === 'open' || c.status === 'draft').length;
  const uniqueRepos = new Set(contributions.map(c => c.repo)).size;
  const totalAdditions = contributions.reduce((acc, c) => acc + (c.stats?.additions || 0), 0);
  const totalDeletions = contributions.reduce((acc, c) => acc + (c.stats?.deletions || 0), 0);
  const totalFilesChanged = contributions.reduce((acc, c) => acc + (c.stats?.filesChanged || 0), 0);

  const lines: string[] = [];

  lines.push(`# ${profileConfig.siteTitle} - Full Text Dump`);
  lines.push(`> ${profileConfig.siteDescription}`);
  lines.push('');
  lines.push('---');
  lines.push(`Author: ${profileConfig.name}`);
  lines.push(`Handle: ${profileConfig.handle}`);
  lines.push(`Personal Website: ${profileConfig.links.website}`);
  lines.push(`GitHub: ${profileConfig.links.github}`);
  lines.push(`LinkedIn: ${profileConfig.links.linkedin}`);
  lines.push(`Showroom Repository: ${profileConfig.links.projectRepo}`);
  lines.push('---');
  lines.push('');
  lines.push('## Bio & Mission');
  lines.push(profileConfig.bio);
  lines.push('');
  lines.push('## Aggregate Statistics');
  lines.push(`- Total Pull Requests Merged: ${totalMerged}`);
  if (totalOpen > 0) {
    lines.push(`- Total Pull Requests In-Review / Active: ${totalOpen}`);
  }
  lines.push(`- Open Source Repositories Impacted: ${uniqueRepos}`);
  lines.push(`- Total Lines of Code Added: +${totalAdditions}`);
  lines.push(`- Total Lines of Code Deleted: -${totalDeletions}`);
  lines.push(`- Total Files Changed: ${totalFilesChanged}`);
  lines.push('');
  lines.push('## Engineering Pipeline Architecture');
  lines.push('The showroom demonstrates how autonomous AI coding agents and human expertise collaborate effectively:');
  lines.push('');
  lines.push('### Stage 1: Issue Discovery (AI Agent)');
  lines.push('- Discovers open issues, reproduction logs, and missing capabilities in high-impact open source repositories.');
  lines.push('- Evaluates feasibility and bounds the problem scope.');
  lines.push('');
  lines.push('### Stage 2: Implementation (AI Agent)');
  lines.push('- Traces control flows and root causes in complex codebases.');
  lines.push('- Authors targeted code changes adhering to project linting, type safety, and formatting conventions.');
  lines.push('- Adds or updates unit, integration, or regression tests to prevent recurrence.');
  lines.push('');
  lines.push('### Stage 3: Verification (Human in the Loop)');
  lines.push('- Personally reviewed and audited by Pere Muñoz.');
  lines.push('- Sanity-checks edge cases, performance implications, architectural fit, and security.');
  lines.push('');
  lines.push('### Stage 4: Maintainer Review & Deployment');
  lines.push('- Submitted upstream via pull requests.');
  lines.push('- Passes repository continuous integration (CI) test suites.');
  lines.push('- Reviewed, approved, and merged into production by project maintainers.');
  lines.push('');
  lines.push('## Detailed Contribution Inventory');
  lines.push('');

  contributions.forEach((c, index) => {
    lines.push(`### ${index + 1}. ${c.repo} - PR #${c.prNumber}`);
    lines.push(`- **Title**: ${c.prTitle}`);
    lines.push(`- **Repository**: [${c.repo}](${c.repoUrl})`);
    lines.push(`- **Pull Request**: [PR #${c.prNumber}](${c.prUrl})`);
    lines.push(`- **Status**: ${c.status.toUpperCase()}`);
    if (c.mergedAt) {
      lines.push(`- **Merged Date**: ${c.mergedAt}`);
    } else if (c.closedAt) {
      lines.push(`- **Closed Date**: ${c.closedAt}`);
    } else if (c.createdAt) {
      lines.push(`- **Opened Date**: ${c.createdAt}`);
    }
    lines.push(`- **Language / Ecosystem**: ${c.language}`);
    if (c.stats) {
      lines.push(`- **Diff Impact**: +${c.stats.additions} additions, -${c.stats.deletions} deletions across ${c.stats.filesChanged} file(s)`);
    }
    lines.push('');
  });

  lines.push('---');
  lines.push('## Machine-Readable Meta');
  lines.push('- Standard: llms.txt (https://llmstxt.org/)');
  lines.push('- Generated by: Astro static build');
  lines.push(`- Canonical URL: https://oss.pere.sh/llms-full.txt`);
  lines.push(`- Summary Endpoint: https://oss.pere.sh/llms.txt`);
  lines.push('');

  return new Response(lines.join('\n'), {
    headers: {
      'Content-Type': 'text/plain; charset=utf-8',
    },
  });
};

